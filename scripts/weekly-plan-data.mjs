function renderList(items, checkbox = false) {
  return items.map((item) => `${checkbox ? "- [ ]" : "-"} ${item}`).join("\n");
}

function renderWeek(week) {
  return `#### ${week.id}｜${week.title}（${week.dates}）\n\n` +
    `> **本周目标：** ${week.goal}\n\n` +
    `**建议投入：** ${week.hours}\n\n` +
    `##### 学习支持\n\n` +
    `- **教材支持：** ${week.textbook}\n` +
    `- **视频支持：** ${week.video}\n` +
    `- **工具 / 模板支持：** ${week.tools}\n\n` +
    `##### 本周关键难点\n\n${week.difficulty}\n\n` +
    `##### 任务清单\n\n${week.tasks.map((task, index) => `${index + 1}. ${task}`).join("\n")}\n\n` +
    `##### 三科融合\n\n${renderList(week.exam)}\n\n` +
    `##### 本周交付物\n\n${renderList(week.outputs, true)}\n\n` +
    `##### 验收标准\n\n${renderList(week.acceptance, true)}\n\n` +
    `##### 忙碌周最低完成线\n\n${week.minimum}\n`;
}

